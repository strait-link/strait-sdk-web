const LIGHT = '--bg:#FFFFFF;--fg:#0F0D0A;--mu:#423B33;--bd:#E8E4DD;--well:#EFECE6;--ac:#FF6A13;--ah:#FF8237;--ap:#E85600;--at:#0F0D0A;--fr:#E85600;--edge:none';
const DARK = '--bg:#191613;--fg:#F6F3EE;--mu:#B8B0A5;--bd:#2B2621;--well:#221E1A;--ac:#FF6A13;--ah:#FF8237;--ap:#E85600;--at:#0F0D0A;--fr:#FF8237;--edge:inset 0 1px 0 rgba(246,243,238,0.05)';
const FONT = "Inter, system-ui, -apple-system, 'Segoe UI', Roboto, sans-serif";
const FAST = '120ms cubic-bezier(0.2, 0.8, 0.2, 1)';
const RADIUS = '8px';
const INK = '#0F0D0A';
const WHITE = '#FFFFFF';
// </tokens>

/** WCAG relative luminance of a #rgb / #rrggbb / rgb() colour, or null for anything else. */
function luminance(c: string): number | null {
  let r: number, g: number, b: number;
  const hex = /^#([0-9a-f]{3}|[0-9a-f]{6})$/i.exec(c.trim());
  const rgb = /^rgba?\(\s*(\d{1,3})[\s,]+(\d{1,3})[\s,]+(\d{1,3})/i.exec(c.trim());
  if (hex) {
    const h = hex[1]!.length === 3 ? hex[1]!.replace(/./g, '$&$&') : hex[1]!;
    [r, g, b] = [0, 2, 4].map((i) => parseInt(h.slice(i, i + 2), 16)) as [number, number, number];
  } else if (rgb) {
    [r, g, b] = [rgb[1], rgb[2], rgb[3]].map(Number) as [number, number, number];
  } else return null;
  const lin = (v: number) => {
    const s = Math.min(255, v) / 255;
    return s <= 0.03928 ? s / 12.92 : ((s + 0.055) / 1.055) ** 2.4;
  };
  return 0.2126 * lin(r) + 0.7152 * lin(g) + 0.0722 * lin(b);
}

/**
 * The text colour that reads best on a custom button colour: ink or white, whichever has the
 * higher contrast (WCAG 2.2, 1.4.3). Null when the colour isn't a plain hex or rgb() value.
 */
export function readableOn(accent: string): string | null {
  const l = luminance(accent);
  if (l == null) return null;
  const vs = (other: number) => (Math.max(l, other) + 0.05) / (Math.min(l, other) + 0.05);
  return vs(luminance(INK)!) >= vs(luminance(WHITE)!) ? INK : WHITE;
}

