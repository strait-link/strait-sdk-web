#!/usr/bin/env node
// tokens.mjs: copies the Strait design tokens (brand v5, DS v5) into this package.
//
//   node scripts/tokens.mjs --brand <path to the brand repo>   # regenerate
//   node scripts/tokens.mjs --check                            # src/banner.ts agrees with src/tokens.ts
//
// It writes two things, both marked GENERATED:
//   1. src/tokens.ts: the semantic colours (light and dark), fonts, radii, shadows and motion,
//      read from brand/tokens/strait-tokens.ts. Internal (not exported); the test suite checks the banner against it.
//   2. The block between `// <tokens>` and `// </tokens>` in src/banner.ts: the CSS custom
//      properties the smart banner uses. banner.ts keeps no imports (dist/banner.js can be
//      copied and served on its own), so its values are written in rather than imported.
// The brand repo is not a dependency (it has no registry release); the generated files are
// committed and the test suite checks they agree. Never edit the values by hand: change the
// tokens in brand/tokens/src, run its build, then run this script.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const TOKENS = path.join(root, 'src/tokens.ts');
const BANNER = path.join(root, 'src/banner.ts');
const START = '// <tokens>';
const END = '// </tokens>';

/** The banner's CSS variables and the semantic token each one takes (DS v5 §3.1). */
export const BANNER_ROLES = {
  '--bg': 'surface', //       the bar itself: a card-level surface on either ground
  '--fg': 'text', //          title
  '--mu': 'text-muted', //    subtitle and the close glyph
  '--bd': 'border', //        the hairline between the bar and the page
  '--well': 'bg-muted', //    placeholder behind the app icon while it loads
  '--ac': 'brand', //         the one action: orange fill
  '--ah': 'brand-hover',
  '--ap': 'brand-press',
  '--at': 'on-brand', //      ink on orange (6.8:1)
  '--fr': 'focus-ring', //    2 px outline, 2 px offset
};

function findBrand(argv) {
  const i = argv.indexOf('--brand');
  const candidates = [
    i >= 0 ? argv[i + 1] : null,
    process.env.STRAIT_BRAND,
    '../brand',
    '../../brand',
    '../co/brand',
    '../../co/brand',
  ].filter(Boolean);
  for (const c of candidates) {
    const f = path.resolve(root, c, 'tokens/strait-tokens.ts');
    if (fs.existsSync(f)) return f;
  }
  throw new Error('brand repo not found: pass --brand <path> or set STRAIT_BRAND');
}

/** Reads one `export const name = {...}` (JSON-shaped) object from the generated TS file. */
function block(src, name) {
  const m = new RegExp(`export const ${name} = (\\{[^\\n]*\\}|\\{[\\s\\S]*?\\n\\})(?: as const)?;`).exec(src);
  if (!m) throw new Error(`strait-tokens.ts: no "${name}" export`);
  return JSON.parse(m[1]);
}

export function readBrand(file) {
  const src = fs.readFileSync(file, 'utf8');
  const version = /export const version = '([^']+)'/.exec(src)?.[1];
  if (!version || Number(version.split('.')[0]) < 5) throw new Error(`need brand tokens v5 or later, found ${version}`);
  return {
    version,
    colors: block(src, 'colors'),
    fonts: block(src, 'fonts'),
    radius: block(src, 'radius'),
    shadows: block(src, 'shadows'),
    motion: block(src, 'motion'),
  };
}

export function tokensFile(t) {
  const j = (o) => JSON.stringify(o, null, 2);
  return `// Strait design tokens v${t.version}: GENERATED by scripts/tokens.mjs from brand/tokens/strait-tokens.ts. Do not edit.
// Spec: DS v5 (design-work/final/DS-V5.md). Orange #FF6A13 is the only accent; neutrals are warm.
// Reduced motion: when (prefers-reduced-motion: reduce) matches, use 0 for every duration.

/** The brand token version these values come from. */
export const version = '${t.version}';

/** Semantic colours, light and dark. Use these, never raw hex. */
export const colors = ${j(t.colors)} as const;

export const fonts = ${j(t.fonts)} as const;

/** Corner radii in px. */
export const radius = ${j(t.radius)} as const;

export const shadows = ${j(t.shadows)} as const;

/** Durations in ms and easing curves. */
export const motion = ${j(t.motion)} as const;
`;
}

/** The generated block that sits inside src/banner.ts. */
export function bannerBlock(t) {
  const vars = (theme) => Object.entries(BANNER_ROLES).map(([v, role]) => {
    const value = t.colors[theme][role];
    if (!value) throw new Error(`token ${theme}.${role} missing`);
    return `${v}:${value}`;
  }).join(';');
  return [
    START,
    `// GENERATED by scripts/tokens.mjs from the Strait tokens v${t.version}. Do not edit.`,
    `const LIGHT = '${vars('light')};--edge:none';`,
    `const DARK = '${vars('dark')};--edge:${t.shadows.dark.edge}';`,
    `const FONT = ${JSON.stringify(t.fonts.body)};`,
    `const FAST = '${t.motion['duration-fast']}ms ${t.motion['ease-enter']}';`,
    `const RADIUS = '${t.radius.md}px';`,
    `const INK = '${t.colors.light['on-brand']}';`,
    `const WHITE = '${t.colors.light['text-inverse']}';`,
    END,
  ].join('\n');
}

function spliceBanner(text, blockText) {
  const a = text.indexOf(START);
  const b = text.indexOf(END);
  if (a < 0 || b < a) throw new Error(`src/banner.ts: needs a ${START} ... ${END} block`);
  return text.slice(0, a) + blockText + text.slice(b + END.length);
}

/** Rebuilds the token values from src/tokens.ts itself (for --check, which needs no brand repo). */
export async function readLocal() {
  const src = fs.readFileSync(TOKENS, 'utf8');
  const version = /export const version = '([^']+)'/.exec(src)?.[1];
  return { version, colors: block(src, 'colors'), fonts: block(src, 'fonts'), radius: block(src, 'radius'), shadows: block(src, 'shadows'), motion: block(src, 'motion') };
}

async function main(argv) {
  if (argv.includes('--check')) {
    const t = await readLocal();
    const want = spliceBanner(fs.readFileSync(BANNER, 'utf8'), bannerBlock(t));
    if (want !== fs.readFileSync(BANNER, 'utf8')) {
      console.error('tokens: src/banner.ts is out of date with src/tokens.ts (run: node scripts/tokens.mjs --brand <path>)');
      return 1;
    }
    console.log(`tokens: in sync (v${t.version})`);
    return 0;
  }
  const t = readBrand(findBrand(argv));
  fs.writeFileSync(TOKENS, tokensFile(t));
  fs.writeFileSync(BANNER, spliceBanner(fs.readFileSync(BANNER, 'utf8'), bannerBlock(t)));
  console.log(`tokens: wrote src/tokens.ts and the banner block (v${t.version})`);
  return 0;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  main(process.argv.slice(2)).then((c) => { process.exitCode = c; }, (e) => { console.error(`tokens: ${e.message}`); process.exitCode = 2; });
}
